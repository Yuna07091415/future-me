export function getLocalizedCategoryName(categoryId, fallbackName, language) {
  if (language === 'uz' || !CATEGORY_TRANSLATIONS[language]) {
    return fallbackName;
  }
  return CATEGORY_TRANSLATIONS[language][categoryId] || fallbackName;
}

export function getLocalizedCareer(career, language) {
  if (!career || language === 'uz' || !CAREER_TRANSLATIONS[language]) {
    return career;
  }
  const tr = CAREER_TRANSLATIONS[language][career.id];
  const localizedCat = getLocalizedCategoryName(career.categoryId, career.category, language);

  if (!tr) {
    return { ...career, category: localizedCat };
  }

  return {
    ...career,
    title: tr.title,
    category: localizedCat,
    shortDescription: tr.shortDescription,
    facts: career.facts
      ? { ...career.facts, demand2030: tr.demand2030 || career.facts.demand2030 }
      : career.facts,
  };
}
