export function getLocalizedQuizQuestions(questions, language) {
  if (language === 'uz' || !QUIZ_TRANSLATIONS[language]) {
    return questions;
  }
  const dict = QUIZ_TRANSLATIONS[language];
  return questions.map((q) => {
    const tr = dict[q.id];
    if (!tr) return q;
    return {
      ...q,
      question: tr.question,
      subtitle: tr.subtitle,
      options: q.options.map((opt, idx) => ({
        ...opt,
        text: tr.options[idx] || opt.text,
      })),
    };
  });
}
